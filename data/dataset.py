import torch
from torch.utils.data import Dataset
import pickle

class BigDataBowlDataset(Dataset):
    """
    Dataset for preprocessed NFL Big Data Bowl data.\\
    Expects a file containing the pickled list of dicts generated by preprocess_folder_into_dataset() in preproccess.py\\
    __getitem__() returns a sample in the format
    ```python
    {
        "pre_xy": torch.Tensor([...]),       # (A, T_pre, 2)
        "traj_S": torch.Tensor([...]),       # (P, T_total, 2)
        "roles": torch.Tensor([...]),        # (A,)
        "ball_landing": torch.Tensor([...]), # (2,)
    }
    ```
    """
    def __init__(self, preprocessed_path: str):
        super().__init__()

        print(f'Reading from {preprocessed_path}...')
        with open(preprocessed_path, "rb") as f:
            self.plays = pickle.load(f)
        print(f"Loaded {len(self.plays)} plays!")

    def __len__(self):
        return len(self.plays)

    def __getitem__(self, idx):
        play = self.plays[idx]

        # Convert numpy arrays → torch tensors
        pre_xy = torch.from_numpy(play["pre_xy"]).float()                       # (A, T_pre, 2)
        post_xy = torch.from_numpy(play["post_xy"]).float()                     # (P, T_post, 2)
        traj_S = torch.cat([pre_xy[:post_xy.shape[0]].clone(), post_xy], dim=1) # (P, T_total, 2)
        roles = torch.from_numpy(play["roles"]).long()            # (A,)
        ball_landing = torch.tensor(play["ball_landing"]).float() # (2,)
        yardline = torch.tensor(play["yardline"]).float()       # (1,)
        direction = torch.tensor(play["direction"]).float()     # (1,)

        # rotate and scale coordinates
        pre_xy[:, :, 0] -= yardline
        pre_xy[:, :, 1] -= 80 / 3
        traj_S[:, :, 0] -= yardline
        traj_S[:, :, 1] -= 80 / 3
        ball_landing[0] -= yardline
        ball_landing[1] -= 80 / 3

        pre_xy[:, :, 0] /= 60
        pre_xy[:, :, 1] /= 80 / 3
        traj_S[:, :, 0] /= 60
        traj_S[:, :, 1] /= 80 / 3
        ball_landing[0] /= 60
        ball_landing[1] /= 80 / 3

        pre_xy *= direction
        traj_S *= direction
        ball_landing *= direction

        return {
            "pre_xy": pre_xy,             # (A, T_pre, 2)
            "traj_S": traj_S,             # (P, T_total, 2)
            "roles": roles,               # (P,)
            "ball_landing": ball_landing, # (2,)
        }

def collate_plays(batch_list: list[dict[str, torch.Tensor]]) -> dict[str, torch.Tensor]:
    """
    Batches a list of samples from BidDataBowlDataset.__getitem__ into a single single dict of batched tensors,
    padding the agent and time dimensions to the max sizes in the list and computes the corresponding masks denoting real/padded tokens.
    Args:
        batch_list (list[dict[str, torch.Tensor]]): list of samples from BidDataBowlDataset.__getitem__
    Returns:
        batch (dict[str, torch.Tensor]): dict of batched tensors:
        ```python
        {
            "pre_xy": torch.Tensor([...]),       # (B, A_max, T_pre_max, 2)
            "traj_S": torch.Tensor([...]),       # (B, P_max, T_total_max, 2)
            "time_remain": torch.Tensor([...]),  # (B, P_max, T_total_max)
            "roles": torch.Tensor([...]),        # (B, A_max)
            "ball_landing": torch.Tensor([...]), # (B, 2)

            "pre_xy_padding_mask": torch.Tensor([...]), # (B, A_max, T_pre_max)
            "traj_S_padding_mask": torch.Tensor([...]), # (B, P_max, T_total_max)
            "roles_padding_mask": torch.Tensor([...]), # (B, A_max)
        }
        ```
    """
    # Compute max batch sizes
    B = len(batch_list)
    A_max       = max(s["pre_xy"].shape[0] for s in batch_list)
    P_max       = max(s["traj_S"].shape[0] for s in batch_list)
    T_pre_max   = max(s["pre_xy"].shape[1] for s in batch_list)
    T_total_max = max(s["traj_S"].shape[1] for s in batch_list)

    # batched tensors
    pre_xy_batch = torch.zeros(B, A_max, T_pre_max, 2, dtype=torch.float32)
    traj_S_batch = torch.zeros(B, P_max, T_total_max, 2, dtype=torch.float32)
    time_remain_batch = torch.zeros(B, P_max, T_total_max, dtype=torch.long)
    roles_batch = torch.zeros(B, A_max, dtype=torch.long)
    ball_landing_batch = torch.zeros(B, 2, dtype=torch.float32)

    # masks
    pre_xy_padding_mask = torch.ones(B, A_max, T_pre_max, dtype=torch.bool)
    traj_S_padding_mask = torch.ones(B, P_max, T_total_max, dtype=torch.bool)
    roles_padding_mask = torch.ones(B, A_max, dtype=torch.bool)

    # fill each play as its slice
    # pre_xy_batch[i] has real data in [0:P, 0:T_pre], 0s elsewhere
    # player_mask[i] True for real players, False for padded
    # pre_time_mask[i] is True for real timestep
    for i, s in enumerate(batch_list):
        A, T_pre, _ = s["pre_xy"].shape
        P, T_total, _ = s["traj_S"].shape

        pre_xy_batch[i, :A, :T_pre, :] = s["pre_xy"]
        traj_S_batch[i, :P, :T_total, :] = s["traj_S"]
        roles_batch[i, :A] = s["roles"]
        ball_landing_batch[i, :] = s["ball_landing"]

        time_remain = torch.arange(T_total - 1, -1, -1, dtype=torch.long)
        time_remain_batch[i, :P, :T_total] = time_remain.unsqueeze(0).expand(P, T_total)

        pre_xy_padding_mask[i, :A, :T_pre] = False
        traj_S_padding_mask[i, :P, :T_total] = False
        roles_padding_mask[i, :A] = False

    return {
        "pre_xy": pre_xy_batch,             # (B, A_max, T_pre_max, 2)
        "traj_S": traj_S_batch,             # (B, P_max, T_total_max, 2)
        "time_remain": time_remain_batch,   # (B, P_max, T_total_max)
        "roles": roles_batch,               # (B, A_max)
        "ball_landing": ball_landing_batch, # (B, 2)

        "pre_xy_padding_mask": pre_xy_padding_mask, # (B, A_max, T_pre_max)
        "traj_S_padding_mask": traj_S_padding_mask, # (B, P_max, T_total_max)
        "roles_padding_mask": roles_padding_mask,   # (B, A_max)
    }