class Encoder(nn.Module):
    """
    A transformer based encoder which takes the PRE-throw position data of ALL players (and thier respective roles)
    and outputs an agent-summary token for each
    """
    def __init__(self):
        super().__init__()
        self.feature_enc = FeatureEncoder(D_MODEL, N_PLAYER_ROLES)
        self.temporal_enc = TemporalEncoder(D_MODEL)
        self.summary_tokens = nn.Embedding(N_PLAYER_ROLES, D_MODEL)
        self.layers = nn.ModuleList([EncoderBlock(D_MODEL, N_HEADS) for _ in range(N_ENC_LAYERS)])
    
    def forward(self, x: torch.Tensor, x_padding_mask: torch.Tensor, roles: torch.Tensor, roles_padding_mask: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x (torch.Tensor): the position data of shape (B, A, T, 2)
            x_padding_mask (torch.Tensor): a binary tensor of shape (B, A, T) where True means the corresponding token in x is padding
            roles (torch.Tensor): the id of each agent of shape (B, A)
            roles_padding_mask (torch.Tensor): a binary tensor of shape (B, A) where True means the corresponding entry in roles is padding
        Returns:
            embeddings (torch.Tensor): a tensor of agent summary tokens of shape (B, A, D)
        """
        B, A, T, D = x.shape
        # encode x into a tensor of embeddings
        x = self.feature_enc(x, roles)
        x = self.temporal_enc(x)                                    # (B, A, T, D)
        # append summary tokens to x and update the padding mask
        summary_tokens = self.summary_tokens(roles)                 # (B, A, D)
        x = torch.cat([summary_tokens.unsqueeze(2), x], dim=2)      # (B, A, T+1, D)
        x_padding_mask = torch.cat([roles_padding_mask.unsqueeze(2), x_padding_mask], dim=2) # (B, A, T+1, D)
        # transform tensor with encoder blocks
        for i in range(N_ENC_LAYERS):
            x = self.layers[i](x, x_padding_mask)
        summary_tokens = x[:, :, -1, :] # (B, A, D)
        return summary_tokens

class BallLandingMLP(nn.Module):
    """
    A small MLP for encoding the ball landing position as a global scene context for the decoder
    """
    def __init__(self):
        super().__init__()
        self.network = nn.Sequential(
            nn.Linear(2, D_MODEL),
            nn.GELU(),
            nn.Linear(D_MODEL, D_MODEL)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        Args:
            x (torch.Tensor): a tensor of ball landing position data of shape (B, 2)
        Returns:
            embedding (torch.Tensor): a tensor of embeddings of shape (B, D)
        """
        x = self.network(x)
        return x
    
class Decoder(nn.Module):
    """
    A transformer based autoregressive decoder which takes trajectory data of a subset of players (and thier respective roles)
    and outputs a prediction for their position in the next frame
    """
    def __init__(self):
        super().__init__()
        self.feature_enc = FeatureEncoder(D_MODEL, N_PLAYER_ROLES)
        self.temporal_enc = DualTemporalEncoder(D_MODEL)
        self.layers = nn.ModuleList([DecoderBlock(D_MODEL, N_HEADS) for _ in range(N_DEC_LAYERS)])
        self.to_residual = nn.Sequential(
            nn.Linear(D_MODEL, D_MODEL),
            nn.GELU(),
            nn.Linear(D_MODEL, 2)
        )
    
    def forward(
            self,
            x: torch.Tensor,
            z: torch.Tensor,
            x_padding_mask: torch.Tensor,
            z_padding_mask: torch.Tensor,
            time_remain: torch.Tensor,
            roles: torch.Tensor
        ) -> torch.Tensor:
        """
        Args:
            x (torch.Tensor): a tensor of shape (B, P, T, 2)
            z (torch.Tensor): a tensor of shape (B, A, D) of encoder outputs
            x_padding_mask (torch.Tensor): a binary tensor of shape (B, P, T) where True means the corresponding token in x is padding
            z_padding_mask (torch.Tensor): a binary tensor of shape (B, A) where True means the corresponding token in z is padding
            time_remain (Tensor): (B, A, T) long tensor representing how much time is left in the play
            roles (torch.Tensor): the id of each agent of shape (B, P)
        Returns:
            prediction (torch.Tensor): a tensor of shape (B, A, T, 2) of predicted positions
        """
        pos = x
        # encode x into a tensor of embeddings
        x = self.feature_enc(x, roles)
        x = self.temporal_enc(x, time_remain) # (B, P, T, D)
        # transform tensor with decoder blocks
        for i in range(N_DEC_LAYERS):
            print('Hello World!', i)
            x = self.layers[i](x, z, x_padding_mask, z_padding_mask)
        # compute predicted outputs
        residual = self.to_residual(x)
        return pos + residual

class BigDataBowlModelV1(nn.Module):
    """
    The full Encoder-Decoder based model
    """
    def __init__(self, encoder: Encoder, ball_landing_mlp: BallLandingMLP, decoder: Decoder):
        super().__init__()
        self.encoder = encoder
        self.ball_landing_mlp = ball_landing_mlp
        self.decoder = decoder
    
    def forward(
            self,
            pre_xy: torch.Tensor,
            traj_S: torch.Tensor,
            time_remain: torch.Tensor,
            roles: torch.Tensor,
            ball_landing: torch.Tensor,
            pre_xy_padding_mask: torch.Tensor,
            traj_S_padding_mask: torch.Tensor,
            roles_padding_mask: torch.Tensor,
        ) -> torch.Tensor:
        """
        Args:
            pre_xy (torch.Tensor): a tensor of shape (B, A, T_pre, 2) of x, y positions
            traj_S (torch.Tensor): a tensor of shape (B, P, T_total, 2) of x, y positions
            time_remain (Tensor): (B, A, T) long tensor representing how much time is left in the play
            roles (torch.Tensor): a tensor of shape (B, A) of player_role ids
            ball_landing (torch.Tensor): a tensor of shape (B, 2) of x, y positions
            pre_xy_padding_mask (torch.Tensor): a binary tensor of shape (B, A, T_pre) where True means the corresponding input in pre_xy is padding
            traj_S_padding_mask (torch.Tensor): a binary tensor of shape (B, P, T_total) where True means the corresponding input in traj_S is padding
            roles_padding_mask (torch.Tensor): a binary tensor of shape (B, A) where True means the corresponding input in roles is padding
        Returns:
            prediction (torch.Tensor): a tensor of shape (B, A, T, 2) of predicted position residuals
        """
        B, A, T_pre, _ = pre_xy.shape
        _, P, T_total, _ = traj_S.shape
        # compute agent summaries
        z = self.encoder(pre_xy, pre_xy_padding_mask, roles, roles_padding_mask) # (B, A, D)
        # append ball landing encoding to agent summaries and update mask
        ball_enc = self.ball_landing_mlp(ball_landing)       # (B, D)
        z = torch.cat([ball_enc.unsqueeze(1), z], dim=1)     # (B, A + 1, D)
        z_padding_mask = torch.cat([torch.zeros((B, 1), dtype=torch.bool, device=z.device), roles_padding_mask], dim=1) # (B, A + 1)
        # compute predictions
        roles_S = roles[:, :P] # (B, P)
        prediction = self.decoder(traj_S, z, traj_S_padding_mask, z_padding_mask, time_remain, roles_S)
        return prediction