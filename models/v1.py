N_ENC_LAYERS = 3
N_DEC_LAYERS = 3

N_PLAYER_ROLES = 4

"""
Big Data Bowl Architecture V1:
    Encoder: generate agent-summary tokens (one for each player)
        Accomplished by appending a extra layer to the time dimension of the (B, A, T, D) data tensor.
        This extra layer is initialized with a learnt initial token for each player type.
        These tokens accumulate information through the attention mechanism
        At the end these token are sliced back out, the final shape is (B, A, D)

    BallLandingMLP: encode the ball landing position as context
        Once appended to the encoder output, the final shape of the "context" tensor is (B, A + 1, D)

    Decoder: generates a prediction for the next frame of a (B, P, T, 2) tracking data tensor.
        Attends to the A + 1 embeddings generated by the Encoder and BallLandingMLP, respectively

Possible Changes
    Multimodal motion prediction: predict K modes of next-step outcomes weighted by a probaility vector
        At inference, we can search for the path with highest accumulated probability
"""

